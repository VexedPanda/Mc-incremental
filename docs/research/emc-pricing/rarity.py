"""Rarity prices for GT raw materials (VexedPanda/Mc-incremental#55).

Usage: python3 rarity.py [ore_counts.json ore_yields.json] > rarity.json

Rarity is how much of a material turns up per Run, across all dimensions: for every ore block, its mean count per Run
area (overworld 3x3 chunks + the Nether and End areas at the Run's coordinates, ore_counts.json) times what fully
processing it yields (ore_yields.json): its crushed ores' material unit, the chanced byproducts of crushing it and the
byproducts of GT's standard route for each crushed ore (washer, thermal centrifuge, macerator).

Value scale: a power law in rarity, anchored at iron (a material as common as iron is worth iron's 256):

    value(M) = 256 * (f_iron / f_M) ** k

rounded to the nearest power of two (ProjectE's own value scale) and clamped to [MIN_VALUE, MAX_VALUE].

The exponent k is fitted (least squares in log space) to ProjectE's own default values for the metals it prices and
the Pack mines (FIT_POINTS: lead 512, silver 512, platinum 4096), against their measured frequency. The ticket's
second anchor, "as rare as diamond is worth diamond's 8192", is printed but not used: vanilla diamond ore is so
plentiful in a Run (about 223 blocks) that diamond is only 4.7 times rarer than iron, which forces k = 2.25 and prices
boron and tantalum near a billion EMC. Gold and nickel are not fit points: nether gold ore and the nickel vein make them
about as common as iron, yet ProjectE values them at 8 and 4 iron. Set EXPONENT to override the fit.

Only materials no recipe values get these prices (see generate.py); the rest come from their ingots and ProjectE.
"""
import json, math, os, sys

ANCHOR_COMMON, ANCHOR_COMMON_VALUE = 'iron', 256
ANCHOR_RARE, ANCHOR_RARE_VALUE = 'diamond', 8192
FIT_POINTS = {'lead': 512, 'silver': 512, 'platinum': 4096}
EXPONENT = None  # None: fit to FIT_POINTS
MIN_VALUE = 16
MAX_VALUE = 32768  # 2^15, four diamonds; a dial, see docs/pocs/poc-1.md

# Ore blocks GT has no macerator recipe for: what one block yields when mined.
VANILLA_DROPS = {'minecraft:nether_quartz_ore': ('nether_quartz', 1.0)}


def frequencies(counts, yields):
    ores, crushed = yields['ores'], yields['crushed']
    f = {}

    def add(m, n):
        f[m] = f.get(m, 0.0) + n

    for dim in counts.values():
        for block, mean in dim['mean_ore_blocks'].items():
            if block in VANILLA_DROPS:
                m, n = VANILLA_DROPS[block]
                add(m, mean * n)
                continue
            o = ores.get(block)
            if o is None:
                continue
            mat, count, byproducts = o
            (unit, amount), route = crushed[mat]
            add(unit, mean * count * amount)
            for m, n in byproducts.items():
                add(m, mean * n)
            for m, n in route.items():
                add(m, mean * count * n)
    return f


def diamond_anchor_exponent(f):
    return math.log(ANCHOR_RARE_VALUE / ANCHOR_COMMON_VALUE) / math.log(f[ANCHOR_COMMON] / f[ANCHOR_RARE])


def fitted_exponent(f):
    xs = [math.log(f[ANCHOR_COMMON] / f[m]) for m in FIT_POINTS]
    ys = [math.log(v / ANCHOR_COMMON_VALUE) for v in FIT_POINTS.values()]
    return sum(x * y for x, y in zip(xs, ys)) / sum(x * x for x in xs)


def price(f):
    k = EXPONENT if EXPONENT is not None else fitted_exponent(f)
    values = {}
    for m, fm in f.items():
        if fm <= 0:
            continue
        raw = ANCHOR_COMMON_VALUE * (f[ANCHOR_COMMON] / fm) ** k
        v = 2 ** round(math.log2(raw))
        values[m] = int(min(MAX_VALUE, max(MIN_VALUE, v)))
    return k, values


def main(argv):
    here = os.path.dirname(os.path.abspath(__file__))
    cf, yf = argv if len(argv) == 2 else (os.path.join(here, 'ore_counts.json'), os.path.join(here, 'ore_yields.json'))
    f = frequencies(json.load(open(cf)), json.load(open(yf)))
    k, values = price(f)
    out = {'comment': 'Generated by rarity.py: per-Run frequency (material units per Run, all dimensions) and EMC value.',
           'exponent': round(k, 4), 'diamond_anchor_exponent': round(diamond_anchor_exponent(f), 4),
           'anchor': {ANCHOR_COMMON: ANCHOR_COMMON_VALUE}, 'fit_points': FIT_POINTS,
           'materials': {m: {'per_run': round(f[m], 3), 'emc': values[m]} for m in sorted(values)}}
    json.dump(out, sys.stdout, indent=1)
    sys.stdout.write('\n')


if __name__ == '__main__':
    main(sys.argv[1:])
